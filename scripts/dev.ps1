<#
.SYNOPSIS
  Run Faultbox locally on Windows.

.DESCRIPTION
  On first run, creates .env in the repo root with a random FAULTBOX_SECRET
  and a random admin password. Then loads .env and runs the server with
  `go run`. Variables already set in your shell take priority over .env.
  Any arguments are passed to faultbox, for example:

    .\scripts\dev.ps1
    .\scripts\dev.ps1 version
    'a-long-password' | .\scripts\dev.ps1 user create --email me@example.com

  If scripts are blocked by your execution policy, run:
    powershell -ExecutionPolicy Bypass -File .\scripts\dev.ps1
#>
$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$envFile = Join-Path $root '.env'

if (-not (Get-Command go -ErrorAction SilentlyContinue)) {
    Write-Error 'Go is not installed or not on PATH. Install it from https://go.dev/dl/'
}

function New-RandomString([int]$bytes) {
    $buf = New-Object byte[] $bytes
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($buf) } finally { $rng.Dispose() }
    return [Convert]::ToBase64String($buf)
}

if (-not (Test-Path $envFile)) {
    $secret = New-RandomString 48
    # URL-safe characters only, so the password is easy to type and paste.
    $password = (New-RandomString 18) -replace '[+/=]', ''
    $content = @"
# Local development settings for Faultbox. Generated by scripts/dev.ps1.
# This file is git-ignored. Keep FAULTBOX_SECRET stable between runs.
FAULTBOX_SECRET=$secret
FAULTBOX_PORT=8080
FAULTBOX_DATABASE_PATH=data/faultbox.db
FAULTBOX_LOG_LEVEL=info

# Used only to create the first dashboard user, while the database has none.
FAULTBOX_ADMIN_EMAIL=admin@example.com
FAULTBOX_ADMIN_PASSWORD=$password
"@
    # UTF-8 without a BOM, so scripts/dev.sh can read the same file.
    [System.IO.File]::WriteAllText($envFile, ($content -replace "`r`n", "`n") + "`n", (New-Object System.Text.UTF8Encoding $false))
    Write-Host "Created .env with a new secret." -ForegroundColor Green
    Write-Host "  Dashboard login: admin@example.com / $password" -ForegroundColor Green
    Write-Host "  (also saved in .env)"
}

foreach ($line in Get-Content -LiteralPath $envFile -Encoding UTF8) {
    $line = $line.Trim()
    if ($line -eq '' -or $line.StartsWith('#')) { continue }
    $eq = $line.IndexOf('=')
    if ($eq -lt 1) { continue }
    $name = $line.Substring(0, $eq).Trim()
    $value = $line.Substring($eq + 1).Trim()
    if ($value.Length -ge 2 -and (($value[0] -eq '"' -and $value[-1] -eq '"') -or ($value[0] -eq "'" -and $value[-1] -eq "'"))) {
        $value = $value.Substring(1, $value.Length - 2)
    }
    if (-not [Environment]::GetEnvironmentVariable($name, 'Process')) {
        [Environment]::SetEnvironmentVariable($name, $value, 'Process')
    }
}

Push-Location $root
try {
    if ($args.Count -eq 0) {
        Write-Host "Starting Faultbox on http://localhost:$($env:FAULTBOX_PORT)  (Ctrl+C to stop)" -ForegroundColor Cyan
    }
    # Pass piped input (e.g. a password for `user create`) through to faultbox.
    if ($MyInvocation.ExpectingInput) {
        $input | & go run ./cmd/faultbox @args
    } else {
        & go run ./cmd/faultbox @args
    }
    exit $LASTEXITCODE
} finally {
    Pop-Location
}
