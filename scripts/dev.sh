#!/usr/bin/env sh
# Run Faultbox locally on Linux or macOS.
#
# On first run, creates .env in the repo root with a random FAULTBOX_SECRET
# and a random admin password. Then loads .env and runs the server with
# `go run`. Variables already set in your shell take priority over .env.
# Any arguments are passed to faultbox, for example:
#
#   ./scripts/dev.sh
#   ./scripts/dev.sh version
#   echo 'a-long-password' | ./scripts/dev.sh user create --email me@example.com
set -eu

root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
env_file="$root/.env"

if ! command -v go >/dev/null 2>&1; then
  echo "Go is not installed or not on PATH. Install it from https://go.dev/dl/" >&2
  exit 1
fi

random_base64() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -base64 "$1" | tr -d '\n'
  else
    head -c "$1" /dev/urandom | base64 | tr -d '\n'
  fi
}

if [ ! -f "$env_file" ]; then
  secret=$(random_base64 48)
  # URL-safe characters only, so the password is easy to type and paste.
  password=$(random_base64 18 | tr -d '+/=')
  umask 077
  cat > "$env_file" <<EOF
# Local development settings for Faultbox. Generated by scripts/dev.sh.
# This file is git-ignored. Keep FAULTBOX_SECRET stable between runs.
FAULTBOX_SECRET=$secret
FAULTBOX_PORT=8080
FAULTBOX_DATABASE_PATH=data/faultbox.db
FAULTBOX_LOG_LEVEL=info

# Used only to create the first dashboard user, while the database has none.
FAULTBOX_ADMIN_EMAIL=admin@example.com
FAULTBOX_ADMIN_PASSWORD=$password
EOF
  echo "Created .env with a new secret."
  echo "  Dashboard login: admin@example.com / $password"
  echo "  (also saved in .env)"
fi

# Parse KEY=VALUE lines literally rather than sourcing the file, so values
# are never executed as shell code. Strips a UTF-8 BOM and CRLF endings.
while IFS= read -r line || [ -n "$line" ]; do
  line=$(printf '%s' "$line" | sed -e '1s/^\xEF\xBB\xBF//' -e 's/\r$//' -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//')
  case "$line" in ''|'#'*) continue ;; esac
  case "$line" in *=*) ;; *) continue ;; esac
  name=${line%%=*}
  value=${line#*=}
  name=$(printf '%s' "$name" | sed 's/[[:space:]]*$//')
  case "$name" in *[!A-Za-z0-9_]*|'') continue ;; esac
  case "$value" in
    \"*\") value=${value#\"}; value=${value%\"} ;;
    \'*\') value=${value#\'}; value=${value%\'} ;;
  esac
  # Keep values already set in the environment.
  eval "current=\${$name-}"
  if [ -z "$current" ]; then
    export "$name=$value"
  fi
done < "$env_file"

cd "$root"
if [ "$#" -eq 0 ]; then
  echo "Starting Faultbox on http://localhost:${FAULTBOX_PORT:-8080}  (Ctrl+C to stop)"
fi
exec go run ./cmd/faultbox "$@"
