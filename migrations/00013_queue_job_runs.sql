-- M10 queue job runs: one row per attempt of every queue job the monitored
-- apps run, successful ones included, plus a daily rollup per job class and
-- queue. Both arrive in telemetry batches (POST /api/v1/telemetry),
-- deduplicated by batch ID (telemetry_batches).
--
-- Retention (queue-job-runs.md, J0): successful runs are deleted after the
-- short-lived data period (48 hours by default); released, failed and timed
-- out runs and the rollup are kept for the issue retention period.

-- +goose Up
CREATE TABLE queue_job_runs (
    id              INTEGER PRIMARY KEY,
    project_id      INTEGER NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    uuid            TEXT    NOT NULL,            -- this attempt, generated by the SDK
    job_uuid        TEXT,                        -- the queued job's payload UUID, shared by its attempts
    job_id          TEXT,                        -- the queue's job ID, as queue_failures.job_id
    attempt         INTEGER NOT NULL,
    max_tries       INTEGER,
    environment     TEXT    NOT NULL,
    release         TEXT,
    job_name        TEXT    NOT NULL,            -- displayName: the notification, mailable or listener, not the wrapper
    kind            TEXT    NOT NULL CHECK (kind IN ('job', 'notification', 'mail', 'listener', 'broadcast')),
    queue_name      TEXT    NOT NULL DEFAULT '',
    connection_name TEXT    NOT NULL DEFAULT '',
    outcome         TEXT    NOT NULL CHECK (outcome IN ('succeeded', 'released', 'failed', 'timed_out')),
    duration_ms     INTEGER NOT NULL,
    wait_ms         INTEGER,                     -- NULL when the job was dispatched without the SDK's stamp
    correlation_id  TEXT,
    batch_id        TEXT,                        -- Laravel job batch (Bus::batch), not the telemetry batch
    started_at      INTEGER NOT NULL,
    finished_at     INTEGER NOT NULL
);

-- Recent-runs list, newest first: by project, and by project and filter.
-- Ascending, so a reverse scan returns (finished_at DESC, id DESC).
CREATE INDEX idx_queue_job_runs_project ON queue_job_runs (project_id, finished_at);
CREATE INDEX idx_queue_job_runs_project_job ON queue_job_runs (project_id, job_name, finished_at);
CREATE INDEX idx_queue_job_runs_project_outcome ON queue_job_runs (project_id, outcome, finished_at);
-- Every project at once, and the retention sweep, which deletes successful
-- runs and the rest on different schedules.
CREATE INDEX idx_queue_job_runs_finished ON queue_job_runs (finished_at);
CREATE INDEX idx_queue_job_runs_outcome ON queue_job_runs (outcome, finished_at);

-- A failed run links to its failed-job row by queue job ID and attempt.
CREATE INDEX idx_queue_failures_project_job_id ON queue_failures (project_id, job_id, attempts) WHERE job_id IS NOT NULL;

-- Per day, job class, queue and connection. d0..d13 and w0..w13 count runs
-- per duration and queue-wait bucket (bounds in store/jobruns.go), enough
-- for an approximate p50 and p95 without keeping every run.
CREATE TABLE queue_job_daily_counts (
    day             INTEGER NOT NULL,            -- days since the Unix epoch, UTC
    project_id      INTEGER NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    environment     TEXT    NOT NULL,
    job_name        TEXT    NOT NULL,            -- "(other)" past 1,000 names per project a day
    queue_name      TEXT    NOT NULL DEFAULT '',
    connection_name TEXT    NOT NULL DEFAULT '',
    kind            TEXT    NOT NULL,
    runs            INTEGER NOT NULL DEFAULT 0,
    succeeded       INTEGER NOT NULL DEFAULT 0,
    released        INTEGER NOT NULL DEFAULT 0,
    failed          INTEGER NOT NULL DEFAULT 0,
    timed_out       INTEGER NOT NULL DEFAULT 0,
    total_ms        INTEGER NOT NULL DEFAULT 0,
    max_ms          INTEGER NOT NULL DEFAULT 0,
    waited          INTEGER NOT NULL DEFAULT 0,  -- runs with a known queue wait
    total_wait_ms   INTEGER NOT NULL DEFAULT 0,
    max_wait_ms     INTEGER NOT NULL DEFAULT 0,
    d0 INTEGER NOT NULL DEFAULT 0, d1 INTEGER NOT NULL DEFAULT 0, d2 INTEGER NOT NULL DEFAULT 0, d3 INTEGER NOT NULL DEFAULT 0,
    d4 INTEGER NOT NULL DEFAULT 0, d5 INTEGER NOT NULL DEFAULT 0, d6 INTEGER NOT NULL DEFAULT 0, d7 INTEGER NOT NULL DEFAULT 0,
    d8 INTEGER NOT NULL DEFAULT 0, d9 INTEGER NOT NULL DEFAULT 0, d10 INTEGER NOT NULL DEFAULT 0, d11 INTEGER NOT NULL DEFAULT 0,
    d12 INTEGER NOT NULL DEFAULT 0, d13 INTEGER NOT NULL DEFAULT 0,
    w0 INTEGER NOT NULL DEFAULT 0, w1 INTEGER NOT NULL DEFAULT 0, w2 INTEGER NOT NULL DEFAULT 0, w3 INTEGER NOT NULL DEFAULT 0,
    w4 INTEGER NOT NULL DEFAULT 0, w5 INTEGER NOT NULL DEFAULT 0, w6 INTEGER NOT NULL DEFAULT 0, w7 INTEGER NOT NULL DEFAULT 0,
    w8 INTEGER NOT NULL DEFAULT 0, w9 INTEGER NOT NULL DEFAULT 0, w10 INTEGER NOT NULL DEFAULT 0, w11 INTEGER NOT NULL DEFAULT 0,
    w12 INTEGER NOT NULL DEFAULT 0, w13 INTEGER NOT NULL DEFAULT 0,
    last_run_at     INTEGER NOT NULL,
    last_outcome    TEXT    NOT NULL,
    PRIMARY KEY (day, project_id, environment, job_name, queue_name, connection_name)
) WITHOUT ROWID;

CREATE INDEX idx_queue_job_daily_counts_project ON queue_job_daily_counts (project_id, day);

